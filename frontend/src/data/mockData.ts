export interface Supplier {
  id: string;
  name: string;
  country: string;
  countryCode: string;
  city: string;
  industry: string;
  commodity: string;
  tier: 'Platinum' | 'Gold' | 'Silver' | 'Bronze';
  qualityScore: number; // 0-100
  deliveryScore: number; // 0-100
  costScore: number; // 0-100
  sustainabilityScore: number; // 0-100
  riskScore: number; // 0-100
  riskLevel: 'Low' | 'Medium' | 'High';
  financialStability: number;
  operationalRisk: number;
  geopoliticalRisk: number;
  complianceRisk: number;
  contactPerson: string;
  email: string;
  phone: string;
  address: string;
  certifications: string[];
  annualSpend: number;
  status: 'Active' | 'Under Review' | 'Suspended';
  leadTimeDays: number;
  onTimeDeliveryRate: number;
}

export interface PurchaseOrder {
  id: string;
  supplierId: string;
  supplierName: string;
  commodity: string;
  itemDescription: string;
  quantity: number;
  unit: string;
  unitPrice: number;
  totalAmount: number;
  orderDate: string;
  expectedDelivery: string;
  actualDelivery?: string;
  status: 'Delivered' | 'In Transit' | 'Pending' | 'Delayed' | 'Cancelled';
  paymentTerms: string;
  buyer: string;
}

export interface Customer {
  id: string;
  name: string;
  industry: string;
  tier: 'Strategic' | 'Enterprise' | 'Growth';
  city: string;
  country: string;
  totalSpend: number;
  satisfaction: number; // 0-100
  retention: number; // 0-100
  nps: number; // -100 to 100
  status: 'Active' | 'Contract Renewal' | 'Review';
  activeContracts: number;
  accountManager: string;
}

export interface InventoryItem {
  id: string;
  sku: string;
  name: string;
  category: string;
  currentStock: number;
  maxCapacity: number;
  reorderPoint: number;
  unitCost: number;
  totalValue: number;
  warehouseLocation: string; // e.g. A-12, B-04
  shelfPosition: [number, number, number]; // [x, y, z] for 3D view
  turnoverRate: number;
  status: 'Healthy' | 'Low Stock' | 'Critical' | 'Overstock';
}

export interface CommodityPriceHistory {
  date: string;
  price: number;
  forecast?: number;
  lowerBound?: number;
  upperBound?: number;
}

export interface ActivityEvent {
  id: string;
  title: string;
  description: string;
  timestamp: string;
  type: 'order' | 'supplier' | 'risk' | 'system';
  severity?: 'normal' | 'warning' | 'critical';
}

export interface UserAccount {
  id: string;
  email: string;
  name: string;
  role: 'Admin' | 'Procurement Manager' | 'Analyst';
  avatar?: string;
}


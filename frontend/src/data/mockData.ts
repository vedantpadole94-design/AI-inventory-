export const generateCommodityHistory = (commodityId: string): CommodityPriceHistory[] => {
  const baseMap: Record<string, number> = {
    steel: 750,
    aluminum: 2100,
    copper: 8200,
    lithium: 24,
    nickel: 15500,
    silicon: 11,
    wafer: 130,
    crude_oil: 70,
    natural_gas: 3.1,
    cotton: 0.78,
    plastic_resin: 1050,
    neodymium: 75,
    cobalt: 16,
    platinum: 920,
    timber: 490,
  };

  const base = baseMap[commodityId] || 500;
  const history: CommodityPriceHistory[] = [];

  // 60 historical months (5 years)
  for (let m = 60; m >= 1; m--) {
    const d = new Date(2026, 8 - m, 1); // target year 2026
    const trend = Math.sin(m / 5) * (base * 0.15) + (60 - m) * (base * 0.003);
    const noise = (Math.sin(m * 17) * 0.05) * base;
    const price = parseFloat(Math.max(base * 0.4, base + trend + noise).toFixed(2));
    history.push({
      date: `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`,
      price,
    });
  }

  // 3 future forecast months (90 days)
  const lastPrice = history[history.length - 1].price;
  for (let f = 1; f <= 3; f++) {
    const d = new Date(2026, 8 + f, 1);
    const forecastVal = parseFloat((lastPrice * (1 + (f * 0.018))).toFixed(2));
    const margin = forecastVal * 0.04 * f;
    history.push({
      date: `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`,
      price: lastPrice,
      forecast: forecastVal,
      lowerBound: parseFloat((forecastVal - margin).toFixed(2)),
      upperBound: parseFloat((forecastVal + margin).toFixed(2)),
    });
  }

  return history;
};

